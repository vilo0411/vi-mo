/**
 * Thẻ đang đo loại số nào. Tỷ trọng (% GDP) và tốc độ tăng (%/năm) đều có dấu %, rất dễ nhầm,
 * ví dụ tưởng tỷ trọng C + I + G + (X − M) phải cộng lại bằng tốc độ tăng GDP.
 */
export type Measure = { kind: "ty-trong" | "toc-do" | "lai-suat" | "muc"; suffix: string; label: string; explain: string };

const GROWTH_IDS = new Set(["gdp_growth", "cpi", "m2"]);
const RATE_IDS = new Set(["policy_rate", "lending_rate", "fed_rate"]);

export function measureOf(ind: Indicator, unit = ""): Measure {
  if (unit.includes("% GDP"))
    return {
      kind: "ty-trong",
      suffix: "GDP",
      label: "Tỷ trọng trong GDP",
      explain: `Đây là tỷ trọng: ${ind.name.toLowerCase()} chiếm bao nhiêu phần trăm quy mô nền kinh tế, không phải tốc độ tăng.`,
    };
  if (GROWTH_IDS.has(ind.id))
    return {
      kind: "toc-do",
      suffix: "/năm",
      label: "Tốc độ tăng so với năm trước",
      explain: "Đây là tốc độ tăng: phần trăm thay đổi so với năm trước.",
    };
  if (RATE_IDS.has(ind.id)) return { kind: "lai-suat", suffix: "/năm", label: "Lãi suất", explain: "Đây là mức lãi suất tính theo năm." };
  return { kind: "muc", suffix: "", label: "Mức", explain: "" };
}
